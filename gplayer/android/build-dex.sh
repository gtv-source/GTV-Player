#!/bin/bash
# Build GtvClip.java into a dex and embed it in QEMU as ui/gtv-clip-dex.h.
# Run again only after changing GtvClip.java; the generated header is committed.
#
# Needs: a JDK (javac, java) and d8 from Google's r8 jar (downloaded once to
# ~/.cache/gplayer, or pass R8_JAR=/path/to/r8.jar). No Android SDK.
#
#   gplayer/android/build-dex.sh
set -euo pipefail

here=$(cd "$(dirname "$0")" && pwd)
src=$(cd "$here/../.." && pwd)
r8_ver=8.5.35
r8=${R8_JAR:-$HOME/.cache/gplayer/r8-$r8_ver.jar}

if [ ! -f "$r8" ]; then
    mkdir -p "$(dirname "$r8")"
    echo "downloading r8 $r8_ver"
    curl -fsSL -o "$r8" \
        "https://dl.google.com/android/maven2/com/android/tools/r8/$r8_ver/r8-$r8_ver.jar"
fi

work=$(mktemp -d)
trap 'rm -rf "${work:?}"' EXIT

javac --release 8 -nowarn -d "$work/classes" "$here/GtvClip.java"
java -cp "$r8" com.android.tools.r8.D8 --release --min-api 26 \
    --output "$work" "$work"/classes/*.class

out="$src/ui/gtv-clip-dex.h"
{
    echo "/* Generated by gplayer/android/build-dex.sh from GtvClip.java: do not edit. */"
    echo "static const unsigned char GTV_CLIP_DEX[] = {"
    od -An -v -tx1 "$work/classes.dex" | sed -e 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g' -e 's/^/    /'
    echo "};"
} > "$out"
echo "wrote $out ($(stat -c %s "$work/classes.dex") bytes dex)"
